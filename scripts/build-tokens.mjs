import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const tokens = JSON.parse(readFileSync(join(root, "tokens", "tokens.json"), "utf8"));

const toVar = (key) => `--${key}`;
const block = (selector, entries) => {
  const lines = Object.entries(entries)
    .map(([k, v]) => `  ${toVar(k)}: ${v.$value};`)
    .join("\n");
  return `${selector} {\n${lines}\n}`;
};

const light = tokens.color.light;
const dark = tokens.color.dark;
const radius = tokens.radius.base.$value;

const css = `/* GENERATED by scripts/build-tokens.mjs — do not edit by hand.
   Source of truth: tokens/tokens.json (from Figma variables). */
${block(":root", light)}
:root {
  --radius: ${radius};
}

${block(".dark", dark)}
`;

const outPath = join(root, "src", "styles", "tokens.css");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, css);
console.log(`Wrote ${outPath}`);