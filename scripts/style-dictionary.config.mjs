import { resolveSources } from "./token-source.mjs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

/**
 * Custom transform to resolve DTCG aliases
 * Style Dictionary's built-in "attribute/cti" transform creates CTI names,
 * but we need to resolve references like {color.palette.primary.600} to actual values
 */

// Custom format to output CSS with :root and .dark selectors
const cssFormat = {
  name: "css/variables",
  format: function (dictionary) {
    const lightTokens = {};
    const darkTokens = {};
    const rootTokens = {};

    // Separate tokens by theme
    dictionary.allTokens.forEach((token) => {
      // Use path to construct proper names (preserving category structure)
      const path = token.path || [];
      let name = path.join("-");
      // Use $value for DTCG tokens, fall back to value
      const value = token.$value ?? token.value;

      // Check if token belongs to light theme (color.light.*)
      if (path[0] === "color" && path[1] === "light") {
        // Use simple name (last part of path) for color tokens to match original output
        name = path.slice(2).join("-");
        lightTokens[name] = value;
      }
      // Check if token belongs to dark theme (color.dark.*)
      else if (path[0] === "color" && path[1] === "dark") {
        // Use simple name (last part of path) for color tokens to match original output
        name = path.slice(2).join("-");
        darkTokens[name] = value;
      }
      // Other tokens (radius, font-family, spacing, etc.) go to :root
      else {
        // Map radius-base to radius (handle both radius.base and dimension.radius.base)
        if ((path[0] === "radius" && path[1] === "base") ||
            (path[0] === "dimension" && path[1] === "radius" && path[2] === "base")) {
          name = "radius";
        }
        // Map typography.fontFamily.sans to font-family-sans
        if (path[0] === "typography" && path[1] === "fontFamily" && path[2] === "sans") {
          name = "font-family-sans";
        }
        // Map typography.fontFamily.mono to font-family-mono
        if (path[0] === "typography" && path[1] === "fontFamily" && path[2] === "mono") {
          name = "font-family-mono";
        }
        // Add "token-" prefix to spacing tokens to avoid Tailwind conflicts
        // Handle both spacing.1 and dimension.spacing.1
        if (path[0] === "spacing" || (path[0] === "dimension" && path[1] === "spacing")) {
          // Use the last part of the path (the spacing number)
          name = `token-spacing-${path[path.length - 1]}`;
        }
        // Quote font family values
        if (name === "font-family-sans" || name === "font-family-mono") {
          rootTokens[name] = `"${value}"`;
        } else {
          rootTokens[name] = value;
        }
      }
    });

    let css = `/* GENERATED by Style Dictionary — do not edit by hand.
   Source of truth: tokens/tokens.json (from Figma variables). */\n`;

    // Output :root with light theme colors and root tokens
    css += ":root {\n";
    Object.entries(lightTokens).forEach(([name, value]) => {
      css += `  --${name}: ${value};\n`;
    });
    Object.entries(rootTokens).forEach(([name, value]) => {
      css += `  --${name}: ${value};\n`;
    });
    css += "}\n\n";

    // Output .dark with dark theme colors
    if (Object.keys(darkTokens).length > 0) {
      css += ".dark {\n";
      Object.entries(darkTokens).forEach(([name, value]) => {
        css += `  --${name}: ${value};\n`;
      });
      css += "}\n";
    }

    return css;
  },
};

export default function createStyleDictionaryConfig(projectConfig, modeOverride) {
  const sources = resolveSources(projectConfig, modeOverride);

  return {
    source: sources.map((src) => join(root, src)),
    platforms: {
      css: {
        transformGroup: "css",
        transforms: [
          "attribute/cti",
          "name/cti/kebab",
          "color/css",
          "dimension/rem",
          // Custom transform to resolve aliases
          {
            name: "resolve-aliases",
            type: "value",
            matcher: (token) => typeof token.$value === "string" && token.$value.startsWith("{"),
            transformer: (token, platform, dictionary) => {
              const ref = token.$value.slice(1, -1); // Remove { and }
              const parts = ref.split(".");
              let current = dictionary.tokens;

              for (const part of parts) {
                if (current && current[part]) {
                  current = current[part];
                } else {
                  throw new Error(`Unresolved alias reference: ${token.$value} in token ${token.name}`);
                }
              }

              if (current && current.$value !== undefined) {
                return current.$value;
              }
              throw new Error(`Unresolved alias reference: ${token.$value} in token ${token.name}`);
            },
          },
        ],
        files: [
          {
            destination: "tokens.css",
            format: "css/variables",
            options: {
              outputReferences: false,
            },
          },
        ],
      },
    },
  };
}

// Register custom format
export { cssFormat };